function build(p: PlanEntry): ShortAnswer {
  const h = HAND[p.id];
  const asks = [...p.planAsks];
  for (const a of h.asks) if (!asks.includes(a)) asks.push(a);
  return {
    id: p.id,
    n: p.n,
    group: p.group,
    chip: h.chip,
    asks,
    answer: p.answer,
    location: p.location,
    face: p.face,
    keywords: Object.entries(h.keywords).map(([word, weight]) => ({ word, weight })),
  };
}

