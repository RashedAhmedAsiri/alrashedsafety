function build(p: PlanEntry): Scenario {
  const h = HAND[p.id];
  const examples = [...p.planExamples];
  for (const e of h.examples) if (!examples.includes(e)) examples.push(e);
  const s: Scenario = {
    id: p.id,
    mode: p.id === 'intro' ? 'intro' : 'outside',
    n: p.n,
    title: p.title,
    icon: h.icon,
    color: h.color,
    location: p.location,
    weather: p.weather,
    time: p.time,
    order: [...p.order],
    examples,
    keywords: Object.entries(h.keywords).map(([word, weight]) => ({ word, weight })),
  };
  if (p.text) s.text = { opening: p.text.opening, must: [...p.text.must], avoid: [...p.text.avoid], slogan: p.text.slogan };
  if (p.body !== undefined) s.body = p.body;
  if (p.speakingSetup) s.speakingSetup = p.speakingSetup;
  return s;
}

const BUILT = PLAN.map(build);

/** «مَنْ هُوَ الرَّاشِدُ؟», first button in every mode and the off-topic fallback. */
export const INTRO: Scenario = BUILT.find((s) => s.id === 'intro')!;

/** The 17 outside scenarios in plan order (n = 1..17). */
export const OUTSIDE_SCENARIOS: Scenario[] = BUILT.filter((s) => s.mode === 'outside');

/** Outside scenario ids in plan order. */
export const OUTSIDE_SCENARIO_IDS = OUTSIDE_SCENARIOS.map((s) => s.id as OutsideScenarioId);
