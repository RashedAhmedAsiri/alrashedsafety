#!/usr/bin/env node
// Parses docs/plan/Outside_scenarios.md (intro + 17 outside scenarios) and emits the plan fields so
// no Arabic is ever retyped. Plain Node, no dependencies.
//
//   node tools/content/outside.mjs            print the parsed plan as JSON
//   node tools/content/outside.mjs --write    regenerate the GENERATED block in src/content/data/outside.ts
//                                             (everything outside the block, the hand-written part, is kept)
//
// Only markdown is stripped: bold labels, list numbers / bullets and the «» around the intro body.
// Every Arabic character, diacritic, {boy/girl} brace and the `..` in slogans is kept exactly.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const PLAN_FILE = resolve(ROOT, 'docs/plan/Outside_scenarios.md');
export const OUT_FILE = resolve(ROOT, 'src/content/data/outside.ts');
export const BEGIN = '// ---- BEGIN GENERATED by tools/content/outside.mjs from docs/plan/Outside_scenarios.md. Do not edit by hand. ----';
export const END = '// ---- END GENERATED ----';

const HEADING = /^## (\d+)\. (.+) · `([a-z_]+)`$/;

/** Splits "a · b · c" meta lines into { Label: value } using the bold labels. */
function parseMeta(line) {
  const out = {};
  const body = line.replace(/^- /, '');
  for (const part of body.split(' · ')) {
    const m = part.match(/^\*\*([^*]+):\*\* (.*)$/);
    if (!m) throw new Error(`Unreadable meta part: ${part}`);
    out[m[1]] = m[2].trim();
  }
  return out;
}

const firstWord = (s) => s.trim().split(/[\s,(]+/)[0];

function parseSection(lines, n, title, id) {
  const meta = {};
  const entry = { id, n, title };
  let i = 0;
  let list = null; // 'must' | 'avoid' while reading a list
  const text = { opening: null, must: [], avoid: [], slogan: null };
  let speakingSetup;
  let body;
  for (; i < lines.length; i++) {
    const line = lines[i];
    if (/^- \*\*Location:\*\*/.test(line)) Object.assign(meta, parseMeta(line));
    else if (/^- \*\*Example questions:\*\*/.test(line)) Object.assign(meta, parseMeta(line));
    else if (line.startsWith('**Opening:** ')) { text.opening = line.slice('**Opening:** '.length); list = null; }
    else if (line === '**Must:**') list = 'must';
    else if (line === '**Remember:**') list = 'avoid';
    else if (line.startsWith('**Slogan:** ')) { text.slogan = line.slice('**Slogan:** '.length); list = null; }
    else if (line.startsWith('**Speaking setup:** ')) { speakingSetup = line.slice('**Speaking setup:** '.length); list = null; }
    else if (line.startsWith('«') && line.endsWith('»')) body = line.slice(1, -1);
    else if (list === 'must' && /^\d+\. /.test(line)) text.must.push(line.replace(/^\d+\. /, ''));
    else if (list === 'avoid' && line.startsWith('- ')) text.avoid.push(line.slice(2));
    else if (line.startsWith('|') || line.startsWith('**')) list = null;
  }

  const locField = meta.Location;
  const locMatch = locField && locField.match(/`([a-z_]+)`/);
  if (!locMatch) throw new Error(`${id}: no location`);
  entry.location = locMatch[1];
  entry.locationNote = locField;

  const w = meta.Weather;
  if (!w) throw new Error(`${id}: no weather`);
  entry.weather = firstWord(w) === 'current' ? null : firstWord(w);
  entry.weatherNote = w;

  entry.time = meta.Time ? firstWord(meta.Time) : null;
  entry.timeNote = meta.Time ?? null;

  if (!meta.Order) throw new Error(`${id}: no order`);
  entry.order = meta.Order.split(',').map((s) => s.trim());

  entry.planExamples = (meta['Example questions'] ?? '').split(' • ').map((s) => s.trim()).filter(Boolean);

  if (n === 0) {
    if (!body) throw new Error('intro: no «body»');
    entry.body = body;
  } else {
    if (!text.opening || !text.slogan || !text.must.length || !text.avoid.length) throw new Error(`${id}: incomplete text`);
    entry.text = text;
  }
  if (speakingSetup) entry.speakingSetup = speakingSetup;
  return entry;
}

/** Returns [intro, ...17 scenarios] in plan order. */
export function parsePlan(md = readFileSync(PLAN_FILE, 'utf8')) {
  const lines = md.split(/\r?\n/);
  const sections = [];
  let cur = null;
  for (const line of lines) {
    const h = line.match(HEADING);
    if (h) {
      cur = { n: Number(h[1]), title: h[2], id: h[3], lines: [] };
      sections.push(cur);
    } else if (line.startsWith('## ')) {
      cur = null;
    } else if (cur) {
      cur.lines.push(line.trim());
    }
  }
  return sections.map((s) => parseSection(s.lines, s.n, s.title, s.id));
}

// ---------- TypeScript emitter ----------

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const arr = (xs, indent) => (xs.length ? `[\n${xs.map((x) => `${indent}  ${q(x)},`).join('\n')}\n${indent}]` : '[]');

function emitEntry(e) {
  const pad = '    ';
  const out = [];
  out.push(`  {`);
  out.push(`${pad}// ${e.n}. ${e.locationNote} · weather: ${e.weatherNote}${e.timeNote ? ` · time: ${e.timeNote}` : ''}`);
  out.push(`${pad}id: ${q(e.id)}, n: ${e.n}, title: ${q(e.title)},`);
  out.push(`${pad}location: ${q(e.location)}, weather: ${e.weather === null ? 'null' : q(e.weather)}, time: ${e.time === null ? 'null' : q(e.time)},`);
  out.push(`${pad}order: [${e.order.map(q).join(', ')}],`);
  if (e.body !== undefined) out.push(`${pad}body: ${q(e.body)},`);
  if (e.text) {
    out.push(`${pad}text: {`);
    out.push(`${pad}  opening: ${q(e.text.opening)},`);
    out.push(`${pad}  must: ${arr(e.text.must, pad + '  ')},`);
    out.push(`${pad}  avoid: ${arr(e.text.avoid, pad + '  ')},`);
    out.push(`${pad}  slogan: ${q(e.text.slogan)},`);
    out.push(`${pad}},`);
  }
  if (e.speakingSetup) out.push(`${pad}speakingSetup: ${q(e.speakingSetup)},`);
  out.push(`${pad}planExamples: [${e.planExamples.map(q).join(', ')}],`);
  out.push(`  },`);
  return out.join('\n');
}

export function emitGenerated(entries) {
  return [
    BEGIN,
    '/** Outside scenario ids in plan order. */',
    'export type OutsideScenarioId =',
    ...entries.filter((e) => e.n > 0).map((e, i, a) => `  | ${q(e.id)}${i === a.length - 1 ? ';' : ''}`),
    '',
    '/** Plan fields for the intro and the 17 outside scenarios, in plan order. */',
    'const PLAN: PlanEntry[] = [',
    ...entries.map(emitEntry),
    '];',
    END,
  ].join('\n');
}

function writeTs(entries) {
  const src = readFileSync(OUT_FILE, 'utf8');
  const a = src.indexOf(BEGIN);
  const b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error(`Markers not found in ${OUT_FILE}`);
  const next = src.slice(0, a) + emitGenerated(entries) + src.slice(b + END.length);
  if (next !== src) writeFileSync(OUT_FILE, next);
  return next !== src;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const entries = parsePlan();
  if (process.argv.includes('--write')) {
    const changed = writeTs(entries);
    console.log(`${changed ? 'Updated' : 'Unchanged'}: ${OUT_FILE} (${entries.length} entries)`);
  } else {
    console.log(JSON.stringify(entries, null, 2));
  }
}
