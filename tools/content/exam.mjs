#!/usr/bin/env node
// Parses docs/plan/Exam.md (flow lines, judging words, 10 questions, score lines, bands, labels) and
// emits the data so no Arabic is ever retyped. Plain Node, no dependencies.
//
//   node tools/content/exam.mjs            print the parsed plan as JSON
//   node tools/content/exam.mjs --write    regenerate the GENERATED block in src/content/data/exam.ts
//
// Only markdown is stripped (bold labels, bullets, «» quotes). Things the plan says in prose are turned
// into data by small, explicit rules (see the comments at each step); the checker re-derives the pieces.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const PLAN_FILE = resolve(ROOT, 'docs/plan/Exam.md');
export const OUT_FILE = resolve(ROOT, 'src/content/data/exam.ts');
export const BEGIN = '// ---- BEGIN GENERATED by tools/content/exam.mjs from docs/plan/Exam.md. Do not edit by hand. ----';
export const END = '// ---- END GENERATED ----';

export const HEADING = /^### س(\S+) · `([a-z0-9_]+)` · (choice|yes\/no|open) · place `([a-z_]+)`(?: \((.+)\))?$/;
const KINDS = { choice: 'choice', 'yes/no': 'yesno', open: 'open' };
/** Plan face words → Expression ids. */
const FACES = { Proud: 'proud', Happy: 'happy', Gentle: 'gentle', Talking: 'talking', Listening: 'listening' };
const LETTERS = ['أ', 'ب', 'ج'];
const STOP = new Set(['the', 'a', 'an']);

/** English concept label → id: "pinch the nose" → "pinch_nose". */
export const conceptId = (label) => label.toLowerCase().split(/\s+/).filter((w) => !STOP.has(w)).join('_');
const quotes = (s) => [...s.matchAll(/«([^»]+)»/g)].map((m) => m[1]);
const field = (lines, label) => {
  const p = `- **${label}:** `;
  const l = lines.find((x) => x.startsWith(p));
  return l === undefined ? undefined : l.slice(p.length);
};
const dropDot = (s) => s.replace(/\.$/, '');
const bullets = (s) => dropDot(s).split(' • ').map((x) => x.trim());
/** "label (w1، w2) • label2 (w3)" → [{ label, words }] */
const groups = (s) =>
  bullets(s).map((g) => {
    const m = g.match(/^(.+?) \((.+)\)$/);
    if (!m) throw new Error(`Unreadable group «${g}»`);
    return { label: m[1], words: m[2].split('، ').map((w) => w.trim()) };
  });

/** Splits the spoken question into its options: " أ: … ب: … ج: …". */
export function splitOptions(question) {
  const idx = LETTERS.map((L) => question.indexOf(` ${L}: `));
  if (idx.some((i) => i < 0) || !(idx[0] < idx[1] && idx[1] < idx[2])) throw new Error(`No options in «${question}»`);
  return LETTERS.map((L, i) => question.slice(idx[i] + L.length + 3, i < 2 ? idx[i + 1] : undefined).trim());
}

/** "Note: in the girl version the boy line «A» becomes «B»." → braces the differing words of A inside `line`. */
export function applyGirlNote(line, a, b) {
  const wa = a.split(' ');
  const wb = b.split(' ');
  if (wa.length !== wb.length) throw new Error('girl note: word counts differ');
  const marked = wa.map((w, i) => (w === wb[i] ? w : `{${w}/${wb[i]}}`)).join(' ');
  if (!line.includes(a)) throw new Error(`girl note: «${a}» not in line`);
  return line.replace(a, marked);
}

function parseQuestion(h, lines) {
  const q = { id: h[2], n: null, kind: KINDS[h[3]], location: h[4], planNo: h[1] };
  if (h[5]) q.placeNote = h[5];
  q.question = field(lines, 'Question');
  q.correct = field(lines, 'Correct');
  q.wrong = field(lines, 'Wrong');
  const answer = field(lines, 'Answer');
  if (!q.question || !q.correct || !q.wrong || (q.kind !== 'open' && !answer)) throw new Error(`${q.id}: missing question/answer/correct/wrong`);

  if (q.kind === 'choice') {
    const m = answer.match(/^([أبج])\. Spoken variants: (.+)$/);
    if (!m) throw new Error(`${q.id}: unreadable answer «${answer}»`);
    q.answer = m[1];
    q.spoken = bullets(m[2]);
    const pics = bullets(field(lines, 'Pictures') ?? '');
    const texts = splitOptions(q.question);
    if (pics.length !== 3) throw new Error(`${q.id}: need 3 pictures`);
    q.options = LETTERS.map((L, i) => ({ letter: L, text: texts[i], picture: pics[i] }));
  } else if (q.kind === 'yesno') {
    // «لَا.» → 'no', «نَعَمْ.» → 'yes'
    const a = dropDot(answer);
    q.answer = a === 'لَا' ? 'no' : a === 'نَعَمْ' ? 'yes' : null;
    if (!q.answer) throw new Error(`${q.id}: yes/no answer «${answer}»`);
    q.planAnswer = a;
  } else {
    q.concepts = groups(field(lines, 'Concepts')).map((g) => ({ id: conceptId(g.label), label: g.label, words: g.words }));
    const wrong = groups(field(lines, 'Wrong words'));
    q.wrongLabel = wrong.map((g) => g.label).join('; ');
    q.wrongWords = wrong.flatMap((g) => g.words);
    // Pass rules: "at least two concepts and no wrong words" → minConcepts 2;
    // "<label> or <label>, and no wrong words" → requireAnyOf those concept ids. Wrong words always fail.
    const pass = dropDot(field(lines, 'Pass'));
    q.planPass = pass;
    const NUM = { one: 1, two: 2, three: 3 };
    const least = pass.match(/^at least (one|two|three) concepts and no wrong words$/);
    const any = pass.match(/^(.+), and no wrong words$/);
    if (least) q.pass = { minConcepts: NUM[least[1]] };
    else if (any) {
      const ids = any[1].split(' or ').map((l) => {
        const c = q.concepts.find((x) => x.label === l.trim());
        if (!c) throw new Error(`${q.id}: pass names unknown concept «${l}»`);
        return c.id;
      });
      q.pass = { requireAnyOf: ids };
    } else throw new Error(`${q.id}: unreadable pass rule «${pass}»`);
    q.cards = bullets(field(lines, 'Picture cards (fallback)')).map((c) => {
      const correct = c.endsWith(' (correct)');
      return { picture: correct ? c.slice(0, -' (correct)'.length) : c, correct };
    });
  }
  const note = lines.find((l) => l.startsWith('Note: in the girl version the boy line '));
  if (note) {
    const [a, b] = quotes(note);
    const which = q.correct.includes(a) ? 'correct' : q.wrong.includes(a) ? 'wrong' : null;
    if (!which) throw new Error(`${q.id}: girl note line not found`);
    q.girlNote = { field: which, boy: a, girl: b };
    q[which] = applyGirlNote(q[which], a, b);
  }
  return q;
}

export function parsePlan(md = readFileSync(PLAN_FILE, 'utf8')) {
  const lines = md.split(/\r?\n/).map((l) => l.trim());
  const find = (pred, what) => {
    const l = lines.find(pred);
    if (l === undefined) throw new Error(`Exam.md: ${what} not found`);
    return l;
  };

  // Flow lines and labels.
  const askLine = find((l) => l.includes('Alrashed asks: «'), 'phase question line');
  const [phaseQuestion, phaseBefore, phaseAfter, sayBefore, sayAfter] = quotes(askLine);
  const start = quotes(find((l) => l.includes('Alrashed says «'), 'start line'))[0];
  const [retake, classroom] = quotes(find((l) => l.includes('two buttons appear: «'), 'retake buttons'));
  const [yes, no] = quotes(find((l) => l.startsWith('**Leaving early:**'), 'confirm card'));
  const certLine = find((l) => l.startsWith('**Certificate card:**'), 'certificate');
  const [certTitle, logo, school, nameLine] = quotes(certLine);
  const dashboard = quotes(find((l) => l.startsWith('**Teacher dashboard:**'), 'dashboard'))[0];
  const [phasePre, phasePost] = certLine.match(/the phase \(([^)]+)\)/)[1].split(' / ');
  const labels = { phaseBefore, phaseAfter, sayBefore, sayAfter, retake, classroom, yes, no, certTitle, logo, school, nameLine, dashboard, phasePre, phasePost };

  // Judging words.
  const choice = find((l) => l.startsWith('- **Choice:**'), 'choice judging');
  const letterGroups = choice.match(/accept the letter \((.+)\) or/)[1].split(' • ').map((g) => g.split('، '));
  const letters = Object.fromEntries(letterGroups.map((g) => [g[0], g]));
  const yn = find((l) => l.startsWith('- **Yes/no:**'), 'yes/no judging');
  const ynm = yn.match(/yes = (.+) • no = (.+?)\. If both/);
  const judging = { letters, yes: ynm[1].split('، '), no: ynm[2].split('، '), firstWins: true };

  // Questions.
  const questions = [];
  let cur = null;
  for (const l of lines) {
    const h = l.match(HEADING);
    if (h) { cur = { h, lines: [] }; questions.push(cur); continue; }
    if (l.startsWith('## ') || l.startsWith('### ')) { cur = null; continue; }
    if (cur) cur.lines.push(l);
  }
  const parsedQs = questions.map((x, i) => ({ ...parseQuestion(x.h, x.lines), n: i + 1 }));

  // Score lines: template «{…} عَلَى X مِنْ عَشْرٍ»; X words from the list; 0 replaces the whole line.
  const template = quotes(find((l) => l.startsWith('**Score line:**'), 'score template'))[0];
  if (!template.includes(' X ')) throw new Error('score template has no X');
  const zero = quotes(find((l) => l.startsWith('- 0: «'), 'score 0'))[0];
  const one = find((l) => l.startsWith('- 1: '), 'score 1').slice(5);
  const two = find((l) => l.startsWith('- 2: '), 'score 2').slice(5);
  const many = find((l) => l.startsWith('- 3 to 10: '), 'score 3-10').slice('- 3 to 10: '.length);
  const [numList, noun] = many.split(' + ');
  const nums = numList.split(' • ');
  if (nums.length !== 8) throw new Error('need 8 number words for 3..10');
  const x = [null, one, two, ...nums.map((w) => `${w} ${noun}`)];
  const score = x.map((v, i) => (i === 0 ? zero : template.replace(' X ', ` ${v} `)));
  const scorePieces = { template, zero, x: x.slice(1), numberWords: nums, noun };

  // Bands: "**9 to 10:** <Arabic> <English effects>"; faces in the order the plan lists them.
  const faceLine = find((l) => l.startsWith('**Band message** (Face '), 'band faces');
  const bandFaces = faceLine.match(/\(Face ([^)]+)\)/)[1].split(/, | or /).map((f) => FACES[f]);
  const bands = lines
    .filter((l) => /^- \*\*\d+ to \d+:\*\* /.test(l))
    .map((l, i) => {
      const m = l.match(/^- \*\*(\d+) to (\d+):\*\* (.+)$/);
      const cut = m[3].search(/[A-Za-z]/);
      return { min: +m[1], max: +m[2], text: m[3].slice(0, cut).trim(), face: bandFaces[i], effects: m[3].slice(cut).trim() };
    });
  if (bands.length !== 3 || bandFaces.some((f) => !f)) throw new Error('bands unreadable');

  // Feedback faces: "(Face Proud for correct, Gentle for wrong)".
  const fb = find((l) => l.includes('Face Proud for correct'), 'feedback faces').match(/Face (\w+) for correct, (\w+) for wrong/);
  const feedbackFaces = { correct: FACES[fb[1]], wrong: FACES[fb[2]] };

  return { questions: parsedQs, phaseQuestion, start, score, scorePieces, bands, labels, judging, feedbackFaces };
}

// ---------- TypeScript emitter ----------

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const list = (xs) => `[${xs.map(q).join(', ')}]`;

function emitQuestion(e) {
  const p = '    ';
  const o = [`  {`, `${p}// س${e.planNo} · ${e.kind}${e.placeNote ? ` · ${e.placeNote}` : ''}${e.planPass ? ` · pass: ${e.planPass}` : ''}`];
  o.push(`${p}id: ${q(e.id)}, n: ${e.n}, kind: ${q(e.kind)}, location: ${q(e.location)},`);
  o.push(`${p}question: ${q(e.question)},`);
  if (e.options) {
    o.push(`${p}options: [`);
    for (const x of e.options) o.push(`${p}  { letter: ${q(x.letter)}, text: ${q(x.text)}, picture: ${q(x.picture)} },`);
    o.push(`${p}],`);
  }
  if (e.answer) o.push(`${p}answer: ${q(e.answer)},`);
  if (e.spoken) o.push(`${p}spoken: ${list(e.spoken)},`);
  if (e.concepts) {
    o.push(`${p}concepts: [`);
    for (const c of e.concepts) o.push(`${p}  { id: ${q(c.id)}, label: ${q(c.label)}, words: ${list(c.words)} },`);
    o.push(`${p}],`);
    o.push(`${p}wrongWords: ${list(e.wrongWords)}, // ${e.wrongLabel}`);
    o.push(`${p}pass: ${e.pass.minConcepts ? `{ minConcepts: ${e.pass.minConcepts} }` : `{ requireAnyOf: ${list(e.pass.requireAnyOf)} }`},`);
    o.push(`${p}cards: [`);
    for (const c of e.cards) o.push(`${p}  { picture: ${q(c.picture)}, correct: ${c.correct} },`);
    o.push(`${p}],`);
  }
  if (e.girlNote) o.push(`${p}// ${e.girlNote.field}: plan note «${e.girlNote.boy}» → «${e.girlNote.girl}» in the girl version, applied as markup`);
  o.push(`${p}correct: ${q(e.correct)},`);
  o.push(`${p}wrong: ${q(e.wrong)},`);
  o.push(`  },`);
  return o.join('\n');
}

export function emitGenerated(d) {
  const o = [BEGIN];
  o.push('/** Exam question ids in plan order. */', 'export type ExamQuestionId =');
  d.questions.forEach((e, i) => o.push(`  | ${q(e.id)}${i === d.questions.length - 1 ? ';' : ''}`));
  o.push('', '/** The ten questions in the fixed plan order (same for pre and post). */', 'export const EXAM_QUESTIONS: ExamQuestion[] = [');
  for (const e of d.questions) o.push(emitQuestion(e));
  o.push('];', '');
  o.push('/** Score lines 0..10 (template with X filled in; 0 is its own line), bands, phase question, start line. */');
  o.push('export const EXAM_LINES: ExamScoreLines = {');
  o.push(`  score: [`);
  d.score.forEach((s, i) => o.push(`    ${q(s)}, // ${i}`));
  o.push(`  ],`);
  o.push(`  bands: [`);
  for (const b of d.bands) o.push(`    { min: ${b.min}, max: ${b.max}, face: ${q(b.face)}, text: ${q(b.text)} },`);
  o.push(`  ],`);
  o.push(`  phaseQuestion: ${q(d.phaseQuestion)},`);
  o.push(`  start: ${q(d.start)},`);
  o.push('};', '');
  o.push('/** The plan\'s celebration for each band (English, for the exam builder), same order as EXAM_LINES.bands. */');
  o.push(`export const EXAM_BAND_EFFECTS: string[] = ${list(d.bands.map((b) => b.effects))};`, '');
  o.push('/** Faces for the feedback lines. */');
  o.push(`export const EXAM_FEEDBACK_FACES = { correct: ${q(d.feedbackFaces.correct)}, wrong: ${q(d.feedbackFaces.wrong)} } as const satisfies Record<'correct' | 'wrong', Expression>;`, '');
  o.push('/** Plan notes per question that the ExamQuestion shape has no field for. */');
  o.push('export const EXAM_NOTES: Partial<Record<ExamQuestionId, { place?: string; wrongLabel?: string; girlNote?: string }>> = {');
  for (const e of d.questions) {
    const parts = [];
    if (e.placeNote) parts.push(`place: ${q(e.placeNote)}`);
    if (e.wrongLabel) parts.push(`wrongLabel: ${q(e.wrongLabel)}`);
    if (e.girlNote) parts.push(`girlNote: ${q(`${e.girlNote.field}: «${e.girlNote.boy}» → «${e.girlNote.girl}»`)}`);
    if (parts.length) o.push(`  ${e.id}: { ${parts.join(', ')} },`);
  }
  o.push('};', '');
  o.push('/** Judging words from the plan: spoken letter names per choice letter, yes words, no words (first one heard wins). */');
  o.push('export const EXAM_JUDGING = {');
  o.push('  letters: {');
  for (const [k, v] of Object.entries(d.judging.letters)) o.push(`    ${q(k)}: ${list(v)},`);
  o.push('  } as Record<ChoiceLetter, string[]>,');
  o.push(`  yes: ${list(d.judging.yes)},`);
  o.push(`  no: ${list(d.judging.no)},`);
  o.push('};', '');
  o.push('/** On-screen and spoken labels the plan gives for the exam screens (with {boy/girl} markup where the plan has it). */');
  o.push('export const EXAM_LABELS = {');
  for (const [k, v] of Object.entries(d.labels)) o.push(`  ${k}: ${q(v)},`);
  o.push('};');
  o.push(END);
  return o.join('\n');
}

function writeTs(d) {
  const src = readFileSync(OUT_FILE, 'utf8');
  const a = src.indexOf(BEGIN);
  const b = src.indexOf(END, a);
  if (a < 0 || b < a) throw new Error(`Markers not found in ${OUT_FILE}`);
  const next = src.slice(0, a) + emitGenerated(d) + src.slice(b + END.length);
  if (next !== src) writeFileSync(OUT_FILE, next);
  return next !== src;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const d = parsePlan();
  if (process.argv.includes('--write')) console.log(`${writeTs(d) ? 'Updated' : 'Unchanged'}: ${OUT_FILE} (${d.questions.length} questions)`);
  else console.log(JSON.stringify(d, null, 2));
}
