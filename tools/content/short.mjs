#!/usr/bin/env node
// Parses docs/plan/Short_answers.md (45 short answers) and the creative topic chips in
// docs/plan/Voice_and_AI.md, and emits the plan fields so no Arabic is ever retyped. Plain Node.
//
//   node tools/content/short.mjs            print the parsed plan as JSON
//   node tools/content/short.mjs --write    regenerate the GENERATED blocks in
//                                           src/content/data/shortAnswers.ts and creativeChips.ts
//                                           (everything outside the blocks, the hand-written part, is kept)
//
// Only markdown is stripped: list numbers, bullets, bold, backticks and the "Asks:" / "Answer:" labels.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const PLAN_FILE = resolve(ROOT, 'docs/plan/Short_answers.md');
export const VOICE_FILE = resolve(ROOT, 'docs/plan/Voice_and_AI.md');
export const OUT_FILE = resolve(ROOT, 'src/content/data/shortAnswers.ts');
export const CHIPS_FILE = resolve(ROOT, 'src/content/data/creativeChips.ts');
export const BEGIN = '// ---- BEGIN GENERATED by tools/content/short.mjs from docs/plan/Short_answers.md. Do not edit by hand. ----';
export const CHIPS_BEGIN = '// ---- BEGIN GENERATED by tools/content/short.mjs from docs/plan/Voice_and_AI.md. Do not edit by hand. ----';
export const END = '// ---- END GENERATED ----';

/** Plan group heading → ShortAnswer['group']. All six headings have an exact counterpart. */
export const GROUPS = {
  'Fire and first aid': 'fire_first_aid',
  'Corridors, stairs and labs': 'corridors_labs',
  'Heat, water and the canteen': 'heat_canteen',
  'Bus and street': 'bus_street',
  'Car and park': 'car_park',
  General: 'general',
};

/** Plan face name → Expression id (src/core/types.ts). */
export const FACES = {
  Warning: 'warning',
  Gentle: 'gentle',
  Explaining: 'explaining',
  Happy: 'happy',
  Proud: 'proud',
  Lightbulb: 'lightbulb',
  Worried: 'worried',
  Smile: 'smile',
  'Sun and drop': 'sunDrop',
  Thinking: 'thinking',
  Surprised: 'surprised',
  Relieved: 'relieved',
  Focused: 'focused',
  Celebration: 'celebration',
};

export const ENTRY = /^(\d+)\. \*\*`([a-z_]+)`\*\* · Place `([a-z_]+)` · Face (.+)$/;

/** Returns the 45 answers in plan order. */
export function parsePlan(md = readFileSync(PLAN_FILE, 'utf8')) {
  const out = [];
  let group = null;
  let groupHeading = null;
  let cur = null;
  for (const raw of md.split(/\r?\n/)) {
    const line = raw.trim();
    const h = line.match(/^## (.+)$/);
    if (h) {
      cur = null;
      groupHeading = h[1];
      group = GROUPS[groupHeading] ?? null; // "How short answers work" has no entries
      continue;
    }
    const e = line.match(ENTRY);
    if (e) {
      if (!group) throw new Error(`Entry ${e[2]} under unknown heading «${groupHeading}»`);
      const face = FACES[e[4]];
      if (!face) throw new Error(`${e[2]}: unknown face «${e[4]}» (add it to FACES)`);
      cur = { id: e[2], n: Number(e[1]), group, groupHeading, location: e[3], face, planFace: e[4], planAsks: [], answer: null };
      out.push(cur);
      continue;
    }
    if (!cur) continue;
    if (line.startsWith('- Asks: ')) cur.planAsks = line.slice('- Asks: '.length).split(' • ').map((s) => s.trim()).filter(Boolean);
    else if (line.startsWith('- Answer: ')) cur.answer = line.slice('- Answer: '.length);
    else if (line && !line.startsWith('- ')) cur = null;
  }
  for (const a of out) if (!a.answer || !a.planAsks.length) throw new Error(`${a.id}: incomplete`);
  return out;
}

/** The 8 creative-mode topic chips, verbatim. */
export function parseChips(md = readFileSync(VOICE_FILE, 'utf8')) {
  const label = '**Topic chips in the scenarios panel (creative mode):** ';
  const line = md.split(/\r?\n/).find((l) => l.startsWith(label));
  if (!line) throw new Error('Topic chips line not found in Voice_and_AI.md');
  return line.slice(label.length).split(' • ').map((s) => s.trim());
}

// ---------- TypeScript emitter ----------

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export function emitGenerated(entries) {
  const out = [BEGIN, '/** Short answer ids in plan order. */', 'export type ShortAnswerId ='];
  entries.forEach((e, i) => out.push(`  | ${q(e.id)}${i === entries.length - 1 ? ';' : ''}`));
  out.push('', '/** Plan fields for the 45 short answers, in plan order. */', 'const PLAN: PlanEntry[] = [');
  let lastGroup = null;
  for (const e of entries) {
    if (e.groupHeading !== lastGroup) out.push(`  // ${e.groupHeading}`);
    lastGroup = e.groupHeading;
    out.push(`  {`);
    out.push(`    id: ${q(e.id)}, n: ${e.n}, group: ${q(e.group)}, location: ${q(e.location)}, face: ${q(e.face)}, // Face ${e.planFace}`);
    out.push(`    planAsks: [${e.planAsks.map(q).join(', ')}],`);
    out.push(`    answer: ${q(e.answer)},`);
    out.push(`  },`);
  }
  out.push('];', END);
  return out.join('\n');
}

export function emitChips(chips) {
  return [
    CHIPS_BEGIN,
    '/** Creative-mode topic chips for the scenarios panel, in plan order. Tapping one asks it as a question. */',
    'export const CREATIVE_CHIPS: string[] = [',
    ...chips.map((c) => `  ${q(c)},`),
    '];',
    END,
  ].join('\n');
}

function replaceBlock(file, begin, block) {
  const src = readFileSync(file, 'utf8');
  const a = src.indexOf(begin);
  const b = src.indexOf(END, a);
  if (a < 0 || b < a) throw new Error(`Markers not found in ${file}`);
  const next = src.slice(0, a) + block + src.slice(b + END.length);
  if (next !== src) writeFileSync(file, next);
  return next !== src;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const entries = parsePlan();
  const chips = parseChips();
  if (process.argv.includes('--write')) {
    const c1 = replaceBlock(OUT_FILE, BEGIN, emitGenerated(entries));
    const c2 = replaceBlock(CHIPS_FILE, CHIPS_BEGIN, emitChips(chips));
    console.log(`${c1 ? 'Updated' : 'Unchanged'}: ${OUT_FILE} (${entries.length} answers)`);
    console.log(`${c2 ? 'Updated' : 'Unchanged'}: ${CHIPS_FILE} (${chips.length} chips)`);
  } else {
    console.log(JSON.stringify({ answers: entries, chips }, null, 2));
  }
}
